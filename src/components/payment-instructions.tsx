import QRCode from "qrcode";
import { formatMoney } from "@/lib/format";
import { promptPayPayload } from "@/lib/promptpay";
import type { PartySnapshot } from "@/lib/types";

type Seller = PartySnapshot & {
  promptpay_id?: string | null;
  bank_accounts?: { bank: string; account_no: string; account_name: string }[];
};

// "How to pay" block on an invoice: PromptPay QR for the cash still due, plus
// bank details. Reads the seller snapshot so it matches the issued document.
export async function PaymentInstructions({ seller, cashDue, paid = 0 }: { seller: Seller | null; cashDue: number; paid?: number }) {
  const promptpay = seller?.promptpay_id;
  const banks = (seller?.bank_accounts ?? []).filter((b) => b.bank || b.account_no);
  if (!promptpay && banks.length === 0) return null;

  const svg = promptpay
    ? await QRCode.toString(promptPayPayload(promptpay, cashDue), { type: "svg", margin: 1, errorCorrectionLevel: "M" })
    : null;

  return (
    <div className="mt-6 flex flex-wrap items-center gap-6 rounded-xl border border-stone-200 bg-stone-50/70 p-5">
      {svg && (
        <div className="text-center">
          {/* SVG generated by `qrcode` from a digits-only EMVCo payload; no user text. */}
          <div
            className="mx-auto w-36 rounded-lg bg-white p-1.5 ring-1 ring-stone-200"
            role="img"
            aria-label={`QR พร้อมเพย์ ยอด ${formatMoney(cashDue)} บาท`}
            dangerouslySetInnerHTML={{ __html: svg }}
          />
          <p className="mt-1.5 text-xs font-medium text-[#1a3f6f]">PromptPay</p>
        </div>
      )}
      <div className="space-y-2 text-sm">
        <p className="font-semibold">ช่องทางการชำระเงิน</p>
        <p>
          ยอดที่ต้องโอน <span className="text-base font-semibold tabular-nums">{formatMoney(cashDue)}</span> บาท
        </p>
        {paid > 0 && <p className="text-stone-500">(ชำระแล้ว {formatMoney(paid)} บาท)</p>}
        {promptpay && <p className="text-stone-600">พร้อมเพย์: {promptpay}</p>}
        {banks.map((b) => (
          <p key={`${b.bank}-${b.account_no}`} className="text-stone-600">
            {b.bank} เลขที่ {b.account_no}
            {b.account_name && ` (${b.account_name})`}
          </p>
        ))}
      </div>
    </div>
  );
}
